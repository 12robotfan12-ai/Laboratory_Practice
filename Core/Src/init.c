#include "init.h"

void GPIO_Ini(void)
{
    // 1. Включение тактирования портов GPIOB и GPIOF через структуры и макросы CMSIS
    SET_BIT(RCC->AHB1ENR, RCC_AHB1ENR_GPIOBEN | RCC_AHB1ENR_GPIOFEN);

    // 2. Настройка светодиодов платы (PB0 - зеленый, PB7 - синий, PB14 - красный) на ВЫХОД (01b)
    CLEAR_BIT(GPIOB->MODER, GPIO_MODER_MODER0 | GPIO_MODER_MODER7 | GPIO_MODER_MODER14);
    SET_BIT(GPIOB->MODER, GPIO_MODER_MODER0_0 | GPIO_MODER_MODER7_0 | GPIO_MODER_MODER14_0);

    // Настройка средней скорости работы для PB0, PB7, PB14
    SET_BIT(GPIOB->OSPEEDR, GPIO_OSPEEDER_OSPEEDR0_0 | GPIO_OSPEEDER_OSPEEDR7_0 | GPIO_OSPEEDER_OSPEEDR14_0);

    // Гасим светодиоды платы при старте
    WRITE_REG(GPIOB->BSRR, GPIO_BSRR_BR0 | GPIO_BSRR_BR7 | GPIO_BSRR_BR14);

    // 3. Настройка порта GPIOF:
    // Кнопки PF0, PF1, PF2, PF3 -> на ВХОД (00b)
    CLEAR_BIT(GPIOF->MODER, GPIO_MODER_MODER0 | GPIO_MODER_MODER1 | GPIO_MODER_MODER2 | GPIO_MODER_MODER3);

    // Включаем подтяжку к земле (Pull-Down = 10b, бит _1) для PF0, PF1, PF2, PF3
    CLEAR_BIT(GPIOF->PUPDR, GPIO_PUPDR_PUPD0 | GPIO_PUPDR_PUPD1 | GPIO_PUPDR_PUPD2 | GPIO_PUPDR_PUPD3);
    SET_BIT(GPIOF->PUPDR, GPIO_PUPDR_PUPD0_1 | GPIO_PUPDR_PUPD1_1 | GPIO_PUPDR_PUPD2_1 | GPIO_PUPDR_PUPD3_1);

    // Внешние светодиоды PF7, PF8, PF9 -> на ВЫХОД (01b, бит _0)
    CLEAR_BIT(GPIOF->MODER, GPIO_MODER_MODER7 | GPIO_MODER_MODER8 | GPIO_MODER_MODER9);
    SET_BIT(GPIOF->MODER, GPIO_MODER_MODER7_0 | GPIO_MODER_MODER8_0 | GPIO_MODER_MODER9_0);
    SET_BIT(GPIOF->OSPEEDR, GPIO_OSPEEDER_OSPEEDR7_0 | GPIO_OSPEEDER_OSPEEDR8_0 | GPIO_OSPEEDER_OSPEEDR9_0);

    // Гасим внешние светодиоды при старте
    WRITE_REG(GPIOF->BSRR, GPIO_BSRR_BR7 | GPIO_BSRR_BR8 | GPIO_BSRR_BR9);
}