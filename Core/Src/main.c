#include <stdint.h>
#include "init.h"

// Задержка для защиты от дребезга контактов кнопки
void delay(volatile uint32_t count)
{
    while (count--)
        ;
}

int main(void)
{
    GPIO_Ini(); // Инициализация портов GPIO

    uint8_t step = 0;     // Счётчик нажатий управляющей кнопки (PF0) (от 0 до 6)
    uint8_t btn0_old = 0; // Предыдущее состояние кнопки 0 (PF0)

    while (1)
    {
        // Считываем регистр GPIOF_IDR по прямому адресу (0x40021400 + 0x10 = 0x40021410)
        uint32_t idr = (*(volatile uint32_t *)0x40021410UL);

        // Состояние управляющей кнопки на пине PF0
        uint8_t btn0_now = (idr >> 0) % 2;

        // 1) Обработка нажатия управляющей кнопки (PF0)
        if (btn0_now == 1 && btn0_old == 0)
        {
            step++;
            if (step >= 6)
            {
                step = 0; // На 6-е нажатие цикл возвращается в начало (все в режиме кнопок)
            }
            delay(300000); // Пауза от дребезга контактов
        }
        btn0_old = btn0_now;

        // Вспомогательные флаги: в каком режиме сейчас находятся каналы 1, 2 и 3
        // 0 - канал работает от кнопки (светит светодиод на плате, внешний погашен)
        // 1 - канал переключен на внешний светодиод на макетке (светодиод на плате погашен)
        uint8_t ext1_active = (step == 1 || step == 2 || step == 3 || step == 5) ? 1 : 0;
        uint8_t ext2_active = (step == 2 || step == 3 || step == 5) ? 1 : 0;
        uint8_t ext3_active = (step == 3 || step == 5) ? 1 : 0;

        // 2) Работа 1-го канала (Кнопка на PF1 / Светодиод платы PB0 / Внешний светодиод PF7):
        if (!ext1_active) // Режим работы от кнопки PF1
        {
            (*(volatile uint32_t *)0x40021418UL) = (1UL << 23); // Гасим внешний LED 1 (PF7, бит 16+7=23)
            if ((idr >> 1) % 2 != 0)
            {
                (*(volatile uint32_t *)0x40020418UL) = (1UL << 0); // Нажата кнопка -> Зажигаем PB0
            }
            else
            {
                (*(volatile uint32_t *)0x40020418UL) = (1UL << 16); // Отпущена -> Гасим PB0
            }
        }
        else // Режим постоянного свечения внешнего светодиода 1 (PF7)
        {
            (*(volatile uint32_t *)0x40020418UL) = (1UL << 16); // Гасим светодиод на плате (PB0)
            (*(volatile uint32_t *)0x40021418UL) = (1UL << 7);  // Зажигаем внешний LED 1 на макетке (PF7)
        }

        // 3) Работа 2-го канала (Кнопка на PF2 / Светодиод платы PB7 / Внешний светодиод PF8):
        if (!ext2_active) // Режим работы от кнопки PF2
        {
            (*(volatile uint32_t *)0x40021418UL) = (1UL << 24); // Гасим внешний LED 2 (PF8, бит 16+8=24)
            if ((idr >> 2) % 2 != 0)
            {
                (*(volatile uint32_t *)0x40020418UL) = (1UL << 7); // Нажата кнопка -> Зажигаем синий LED (PB7)
            }
            else
            {
                (*(volatile uint32_t *)0x40020418UL) = (1UL << 23); // Отпущена -> Гасим PB7
            }
        }
        else // Режим постоянного свечения внешнего светодиода 2 (PF8)
        {
            (*(volatile uint32_t *)0x40020418UL) = (1UL << 23); // Гасим синий LED на плате (PB7)
            (*(volatile uint32_t *)0x40021418UL) = (1UL << 8);  // Зажигаем внешний LED 2 на макетке (PF8)
        }

        // 4) Работа 3-го канала (Кнопка на PF3 / Светодиод платы PB14 / Внешний светодиод PF9):
        if (!ext3_active) // Режим работы от кнопки PF3
        {
            (*(volatile uint32_t *)0x40021418UL) = (1UL << 25); // Гасим внешний LED 3 (PF9, бит 16+9=25)
            if ((idr >> 3) % 2 != 0)
            {
                (*(volatile uint32_t *)0x40020418UL) = (1UL << 14); // Нажата кнопка -> Зажигаем красный LED (PB14)
            }
            else
            {
                (*(volatile uint32_t *)0x40020418UL) = (1UL << 30); // Отпущена -> Гасим PB14
            }
        }
        else // Режим постоянного свечения внешнего светодиода 3 (PF9)
        {
            (*(volatile uint32_t *)0x40020418UL) = (1UL << 30); // Гасим красный LED на плате (PB14)
            (*(volatile uint32_t *)0x40021418UL) = (1UL << 9);  // Зажигаем внешний LED 3 на макетке (PF9)
        }
    }
}